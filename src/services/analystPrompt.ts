/** Monta o prompt do usuário: SOMENTE dados reais + ordem de execução. */
export function buildAnalystPrompt(i: MorningBriefInput): string {
  const sectors = [
    ...i.sectorsTop.map((s) => `${s.label} ${bSigned(s.chg)}%`),
    ...i.sectorsBottom.map((s) => `${s.label} ${bSigned(s.chg)}%`),
  ].join(' · ') || 'N/A';
  const news = i.news.map((x) => `“${x.title}” (${x.source})`).join(' | ') || 'N/A';
  const elites = i.elites.map((e) => `${e.symbol} score ${e.score} R:R ${e.rr ?? 'N/A'}`).join(' · ') || 'nenhum Elite 80+';
  return [
    `DADOS DO CRIPTONEX (${i.dateBrt}):`,
    `AÇÕES US — S&P 500 ${bNum(i.spx.price)} (${bSigned(i.spx.chg)}%) · Nasdaq 100 ${bNum(i.ndx.price)} (${bSigned(i.ndx.chg)}%) · Dow ${bNum(i.dji.price)} (${bSigned(i.dji.chg)}%).`,
    `VOL — VIX ${bNum(i.vix.level)} (${bSigned(i.vix.chg)}%) · DXY em ${i.dxy.dir ?? 'N/A'} (${bSigned(i.dxy.chg)}%).`,
    `CRIPTO — BTC ${bNum(i.btc.price)} (${bSigned(i.btc.chg24)}% 24h) · ETH ${bNum(i.eth.price)} (${bSigned(i.eth.chg24)}% 24h) · 48h S&P ${bSigned(i.btcCorr48.spx48)}% vs BTC ${bSigned(i.btcCorr48.btc48)}% → ${i.btcCorr48.mode ?? 'inconclusivo'}.`,
    `REGIME: ${i.regime} · amplitude ${i.breadth ?? 'N/A'} · SETORES: ${sectors}.`,
    `NOTÍCIAS 12H: ${news}.`,
    `ELITES 1–3M: ${elites}.`,
    `DIVERGÊNCIAS: ${i.flags.join(' | ') || 'nenhuma'}.`,
    'Execute a análise completa agora, usando EXCLUSIVAMENTE estes dados. Onde faltar dado, escreva "Indisponível".',
    'TAMANHO OBRIGATÓRIO: análise LONGA e detalhada, no mínimo 800 palavras — desenvolva cada seção aplicável com profundidade (contexto, números, confluências, conflitos, riscos). Resposta curta será descartada automaticamente.',
  ].join('\n');
}
